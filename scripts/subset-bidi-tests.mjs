// Regenerates tests/data/BidiCharacterTest-13.0.0.subset.txt: every 25th case of Unicode's
// BidiCharacterTest-13.0.0.txt (the UBA version bidi-js implements), with the Unicode License v3.
// Usage: node scripts/subset-bidi-tests.mjs
import { writeFileSync } from 'node:fs';

const SOURCE = 'https://www.unicode.org/Public/13.0.0/ucd/BidiCharacterTest.txt';
const LICENSE = 'https://www.unicode.org/license.txt';
const EVERY = 25;

const get = async (url) => {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return (await res.text()).replace(/\r\n/g, '\n');
};
const [source, license] = await Promise.all([get(SOURCE), get(LICENSE)]);
const cases = source.split('\n').filter((l) => l.trim() && !l.startsWith('#'));
const kept = cases.filter((_, i) => i % EVERY === 0);
const header = [
  `# Subset of ${SOURCE}`,
  `# Every ${EVERY}th test case (${kept.length} of ${cases.length}), regenerated by scripts/subset-bidi-tests.mjs.`,
  '# Field format: see the header of the source file and tests/support/bidi-character-test.ts.',
  '#',
  ...source
    .split('\n')
    .filter((l) => l.startsWith('#'))
    .slice(0, 3),
  '#',
  ...license
    .trim()
    .split('\n')
    .map((l) => `# ${l}`.trimEnd()),
  '',
];
writeFileSync(
  'tests/data/BidiCharacterTest-13.0.0.subset.txt',
  `${[...header, ...kept].join('\n')}\n`,
);
console.log(`kept ${kept.length} of ${cases.length} cases`);
