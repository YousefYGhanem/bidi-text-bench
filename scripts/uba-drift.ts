// Measures how far the engine (bidi-js, UBA 13.0.0) drifts from current Unicode (ADR-0004):
// 1. BidiCharacterTest.txt for 13.0.0 and 18.0.0 through the engine;
// 2. bidi-js's Bidi_Class for every code point against UCD 18.0.0 DerivedBidiClass.txt.
// Writes the class differences to tests/data/uba-13-vs-18-bidi-class-drift.txt.
// Usage: node scripts/uba-drift.ts
import { writeFileSync } from 'node:fs';
import bidiModule, { type Bidi } from 'bidi-js';
import { runBidiCharacterTest, testCases } from '../tests/support/bidi-character-test.ts';

const UCD = 'https://www.unicode.org/Public';
const get = async (url: string) => {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
};

for (const version of ['13.0.0', '18.0.0']) {
  const cases = testCases(await get(`${UCD}/${version}/ucd/BidiCharacterTest.txt`));
  const failed = cases.filter((line) => runBidiCharacterTest(line) !== null).length;
  console.log(`BidiCharacterTest ${version}: ${cases.length - failed}/${cases.length} pass`);
}

// @missing lines use long property-value names; explicit lines use the short ones.
const SHORT: Record<string, string> = {
  Left_To_Right: 'L',
  Right_To_Left: 'R',
  Arabic_Letter: 'AL',
  European_Number: 'EN',
  European_Separator: 'ES',
  European_Terminator: 'ET',
  Arabic_Number: 'AN',
  Common_Separator: 'CS',
  Nonspacing_Mark: 'NSM',
  Boundary_Neutral: 'BN',
  Paragraph_Separator: 'B',
  Segment_Separator: 'S',
  White_Space: 'WS',
  Other_Neutral: 'ON',
};
const derived = await get(`${UCD}/18.0.0/ucd/extracted/DerivedBidiClass.txt`);
const ucd = new Map<number, string>();
// Explicit lines follow the @missing defaults in the file, so later lines win.
for (const line of derived.split('\n')) {
  const m =
    /^# @missing: ([0-9A-F]+)\.\.([0-9A-F]+); (\w+)/.exec(line) ??
    /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*; (\w+)/.exec(line);
  if (!m) continue;
  const [lo, hi] = [m[1], m[2] ?? m[1]].map((h) => Number.parseInt(h as string, 16)) as [
    number,
    number,
  ];
  for (let cp = lo; cp <= hi; cp++) ucd.set(cp, SHORT[m[3] as string] ?? (m[3] as string));
}

const bidi = (bidiModule as unknown as () => Bidi)();
const hex = (n: number) => n.toString(16).toUpperCase().padStart(4, '0');
const lines: string[] = [];
let count = 0;
let run: { lo: number; hi: number; ucd: string; js: string } | null = null;
const flush = () => {
  if (run)
    lines.push(
      `${hex(run.lo)}${run.hi === run.lo ? '' : `..${hex(run.hi)}`}; ${run.ucd}; ${run.js}`,
    );
};
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const want = ucd.get(cp) ?? 'L';
  const js = bidi.getBidiCharTypeName(String.fromCodePoint(cp));
  if (js === want) continue;
  count++;
  if (run && run.hi === cp - 1 && run.ucd === want && run.js === js) run.hi = cp;
  else {
    flush();
    run = { lo: cp, hi: cp, ucd: want, js };
  }
}
flush();
writeFileSync(
  'tests/data/uba-13-vs-18-bidi-class-drift.txt',
  `# Code points whose Bidi_Class in bidi-js 1.1.0 (UCD 13.0.0) differs from UCD 18.0.0.\n# Regenerated by scripts/uba-drift.ts. Format: range; UCD 18.0.0 class; bidi-js class.\n${lines.join('\n')}\n`,
);
console.log(`Bidi_Class: ${count} code points differ, in ${lines.length} ranges`);
